#!/bin/sh
# Tao cac role voi quyen toi thieu (nguyen tac least privilege)
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" <<EOSQL
CREATE ROLE ${APP_DB_USER} LOGIN PASSWORD '${APP_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE exporter LOGIN PASSWORD '${EXPORTER_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
GRANT pg_monitor TO exporter;
EOSQL
